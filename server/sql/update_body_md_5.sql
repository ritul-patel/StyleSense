A color that clashes with your undertone doesn''t ruin an outfit—it just creates a bit of visual tension near your face, sometimes subtle, sometimes obvious. The word "avoid" here really means "be intentional with," not "delete from your closet forever." Plenty of people wear a "wrong" color beautifully by pairing it smartly—more on that shortly.

Think of this less as a list of banned colors and more as an early warning system—so you know what to expect before you commit to buying something.

## Colors to Approach Carefully by Undertone

**Warm undertone — Colors that often clash:** Icy blue, cool silver-gray, blue-based fuchsia. These lean cool and can make warm skin look slightly sallow or tired.

**Cool undertone — Colors that often clash:** Mustard, burnt orange, warm caramel brown. These lean warm and can make cool skin look slightly flushed or muddy.

**Neutral undertone — Colors that often clash:** Extremely saturated shades at either temperature extreme. Neutral skin generally handles softened, muted versions of colors better than the most intense version.

## Colors to Approach Carefully by Skin Tone

Beyond undertone, skin tone depth also affects which colors sit well—mostly through contrast.

**Fair skin:** very dark, saturated colors worn head-to-toe can sometimes overwhelm, and neon brights right at the neckline can occasionally look harsh. Smaller doses or pairing with a softer neutral usually solves this.

**Light skin:** extremely pale, washed-out pastels close to your own skin tone in value can flatten your whole look rather than lifting it.

**Medium skin:** very muted, low-saturation shades can occasionally look a touch flat compared to the richer colors medium skin often handles beautifully.

**Tan skin:** icy, very cool pastels can sometimes look slightly chalky against warm, golden undertones common in tan skin.

**Deep skin:** muddy, low-contrast neutrals can underwhelm compared to the vividness deep skin can typically carry so well.

## How to Still Wear a Color That Doesn''t Naturally Suit You

Love a color that''s technically "tricky" for your undertone? Here''s how to make it work anyway:

- **Move it away from your face.** Trousers, skirts, and shoes carry far less undertone risk than tops, scarves, or collars.
- **Pair it with a flattering neutral near your face.** A mustard skirt with a cool-toned cream or white top softens mustard''s warm intensity for a cool-undertone wearer.
- **Choose a slightly adjusted version of the shade.** A muted, dustier mustard rather than a pure golden-orange mustard can bridge the gap for cooler undertones.
- **Use it as a small accent.** A bag, a pair of earrings, or a belt lets you enjoy a color without it dominating the space closest to your complexion.

