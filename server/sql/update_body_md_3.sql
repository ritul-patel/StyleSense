Wedding venues are lighting chaos: warm string lights, cool banquet hall fluorescents, dim mandap lighting, harsh flash photography—sometimes all in the same evening. Colors that look great in daylight can shift dramatically under these conditions, which is exactly why "just wear what you always wear" doesn''t always hold up at events.

Generally, warm venue lighting (fairy lights, candles, golden hour outdoor ceremonies) tends to favor warm undertones and richer, saturated colors. Cooler, brighter venue lighting (banquet halls, LED-lit stages) tends to favor cool undertones and colors with more built-in contrast.

## Best Colors by Skin Tone for Weddings

**Fair skin:** Dusty rose, sage, soft gold, burgundy accents. Avoid very pale pastels under bright event lighting—they can wash out in photos.

**Light skin:** Coral, teal, mustard, plum. Handles both muted and richer festive shades well.

**Medium skin:** Emerald, wine, camel, coral. Often the most flexible range for festive colors.

**Tan skin:** Rust, mustard, deep maroon, chocolate brown. Warm, richly saturated shades photograph beautifully.

**Deep skin:** Fuchsia, cobalt, emerald, bright gold. High-saturation festive colors genuinely shine here.

## Best Colors by Undertone for Weddings

**Warm undertone:** gold, rust, mustard, warm maroon, olive with gold embroidery.

**Cool undertone:** emerald, sapphire, true red, fuchsia, silver detailing.

**Neutral undertone:** deep teal, wine, dusty rose with gold or silver accents, whichever metallic you naturally suit better.

